#!/usr/bin/env node
// Regenerate ANIMATIONS.md directly from the pattern/effect code so the doc can
// never drift out of sync with what's actually implemented.

import { writeFileSync } from 'node:fs';
import { PATTERN_NAMES, PATTERN_DESCRIPTIONS } from '../src/patterns.js';
import { EFFECT_NAMES, EFFECT_DESCRIPTIONS } from '../src/effects.js';
import { CATALOG } from '../src/animationCatalog.js';

let md = '';
md += '# Animation Catalog\n\n';
md += '> Generated by `scripts/generate-catalog-doc.js` — do not edit by hand. Run `npm run catalog`.\n\n';
md += `**${CATALOG.length}** forms = **${PATTERN_NAMES.length}** patterns (timing) × **${EFFECT_NAMES.length}** effects (appearance).\n\n`;
md += 'A form name is `<pattern>--<effect>`, e.g. `radial-center--pulse-glow`.\n\n';

md += '## Patterns — when each cell takes its turn\n\n';
for (const p of PATTERN_NAMES) md += `- \`${p}\` — ${PATTERN_DESCRIPTIONS[p] || ''}\n`;

md += '\n## Effects — how a cell looks at its turn\n\n';
for (const e of EFFECT_NAMES) md += `- \`${e}\` — ${EFFECT_DESCRIPTIONS[e] || ''}\n`;

md += '\n## All forms\n\n';
for (const p of PATTERN_NAMES) {
  md += `### ${p}\n\n`;
  for (const e of EFFECT_NAMES) md += `- \`${p}--${e}\`\n`;
  md += '\n';
}

writeFileSync(new URL('../ANIMATIONS.md', import.meta.url), md);
console.log(`Wrote ANIMATIONS.md — ${CATALOG.length} forms.`);
